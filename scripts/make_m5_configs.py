"""Writes configs/experiments/m5_*.yaml. Settings are frozen from M3 (no new tuning); all seeds are fresh (3000+)."""
import copy
import glob
import os
from pathlib import Path

import yaml

OUT = Path("configs/experiments")
for f in glob.glob(str(OUT / "m5_*.yaml")):
    if "m5_trace" not in f:  # written by scripts/make_m5_trace_configs.py
        os.remove(f)
SYN = yaml.safe_load(open(OUT / "m3confirm_a1_local_geometric.yaml"))["methods"]
ELE = yaml.safe_load(open(OUT / "m3confirm_elec2.yaml"))["methods"]
WCP = {"type": "weighted_cp", "window": 500, "recent": 500, "refit_every": 200, "clip": 10.0, "label": "weighted_cp"}
EVAL = {"window": 100, "burn_in": 500}
JUMP = {"kind": "mean", "regions": [1], "start": 3000, "size": 0.6, "profile": "abrupt"}
TWO = {"use": "synthetic_two_region"}
SIX = {"use": "synthetic_two_region", "n_regions": 6, "n_rounds": 12000, "region_weights": None}
ALT = [1, 300, 1, 300, 1, 300]
TENT = [0.3, 0.6, 0.6, 0.6, 0.6, 0.3]
SIX_SHIFT = [{"kind": "mean", "size_per_region": TENT, "start": 6000, "profile": "abrupt"}]
GEO = {"type": "geometric", "per_region": [1, 100], "d_max": 500}

D = {
    "a01_local_geometric": (TWO, GEO, [JUMP]),
    "a02_local_fixed": (TWO, {"type": "fixed", "per_region": [1, 100]}, [JUMP]),
    "a03_smooth_alternating": (SIX, {"type": "geometric", "per_region": ALT, "d_max": 1500}, SIX_SHIFT),
    "a04_smooth_gradient": (SIX, {"type": "geometric", "per_region": [1, 30, 75, 150, 300, 500], "d_max": 1500}, SIX_SHIFT),
    "a05_nonsmooth_fast_only": (SIX, {"type": "geometric", "per_region": ALT, "d_max": 1500},
                                [{"kind": "mean", "size_per_region": [0.6, 0, 0.6, 0, 0.6, 0], "start": 6000, "profile": "abrupt"}]),
    # Held-out designs: none of these influenced any setting.
    "a06_gradual": (TWO, GEO, [dict(JUMP, profile="gradual", duration=1000)]),
    "a07_recurring": (TWO, GEO, [dict(JUMP, profile="recurring", period=1000, start=2000)]),
    "a08_variance": (TWO, GEO, [{"kind": "variance", "regions": [1], "start": 3000, "size": 1.5, "profile": "abrupt"}]),
    "a09_covariate_and_mean": (TWO, GEO, [JUMP, {"kind": "covariate", "regions": [1], "start": 3000, "size": 2.0, "profile": "abrupt"}]),
    "a10_y_dependent_delay": (TWO, {"type": "y_dependent", "base": {"type": "geometric", "per_region": [1, 100]}, "y_coef": 0.5, "d_max": 500}, [JUMP]),
    "a11_heavy_tailed_delay": (TWO, {"type": "pareto", "per_region": [1, 20], "shape": 1.2, "d_max": 2000}, [JUMP]),
    "a12_continuous_x_delay": (SIX, {"type": "x_continuous", "min_mean": 1, "max_mean": 300, "power": 1.0, "d_max": 1500}, SIX_SHIFT),
}


def write(name, exp):
    (OUT / f"m5_{name}.yaml").write_text("# Generated by scripts/make_m5_configs.py. Pre-registered in reports/decisions.md (M5 protocol).\n"
                                         + yaml.safe_dump(exp, sort_keys=False))


def syn(name, ds, delay, shifts, methods=None, alpha=0.1, seeds=100, extra_ds=None):
    write(name, {"name": f"m5_{name}", "alpha": alpha, "dataset": dict(ds, **(extra_ds or {})), "delay": delay, "shifts": shifts, "eval": EVAL,
                 "runtime": {"log_every": 2000}, "methods": copy.deepcopy(methods or SYN + [WCP]), "seeds": {"start": 3000, "count": seeds}})


def elec(name, alpha=0.1, extra_ds=None):
    write(name, {"name": f"m5_{name}", "alpha": alpha, "dataset": dict({"use": "elec2", "segment": 0}, **(extra_ds or {})),
                 "delay": {"type": "geometric", "per_region": [1, 20, 100], "d_max": 500}, "shifts": [], "eval": {"window": 100, "burn_in": 300},
                 "runtime": {"log_every": 2000}, "methods": copy.deepcopy(ELE + [WCP]), "seeds": {"start": 3000, "count": 10},
                 "grid": {"dataset.segment": list(range(10))}})


for k, (ds, dl, sh) in D.items():
    syn(k, ds, dl, sh)
elec("elec2")
# Sensitivity: alpha = 0.05 with the same settings
for k in ("a01_local_geometric", "a03_smooth_alternating", "a06_gradual"):
    syn(f"alpha05_{k}", *D[k], alpha=0.05)
elec("alpha05_elec2", alpha=0.05)
# Robustness: CQR scores
for k in ("a01_local_geometric", "a03_smooth_alternating", "a08_variance"):
    syn(f"cqr_{k}", *D[k], extra_ds={"cqr": True})
elec("cqr_elec2", extra_ds={"cqr": True})
# Gap against delay heterogeneity (figure F5)
pick = [m for m in SYN if m["label"] in ("aci_g0.02_p", "regional_aci_g0.05_p", "olcp_g0.02", "dalo_agei25_e0.05_b", "dalo_oracle")]
oracles = [{"use": "regional_aci", "gamma": 0.05, "project": True, "oracle_no_delay": True, "label": "regional_aci_oracle"}]
for kind, dl in (("fixed", {"type": "fixed", "per_region": [1, 1]}), ("geometric", {"type": "geometric", "per_region": [1, 1], "d_max": 4000})):
    exp = {"name": f"m5_f5_{kind}", "alpha": 0.1, "dataset": TWO, "delay": dl, "shifts": [JUMP], "eval": EVAL, "runtime": {"log_every": 2000},
           "methods": copy.deepcopy(pick + oracles), "seeds": {"start": 3000, "count": 100},
           "grid": {"delay.per_region": [[1, m] for m in (1, 5, 20, 50, 100, 200, 400)]}}
    write(f"f5_{kind}", exp)
# Sensitivity of DALO-CP to one setting at a time (figure F10)
BASE = next(m for m in SYN if m["label"] == "dalo_agei25_e0.05_b")
f10 = [copy.deepcopy(BASE)]
for e in (0.02, 0.1, 0.2, 0.5):
    f10.append(dict(copy.deepcopy(BASE), eta_rel=e, label=f"f10_eta{e}"))
for t in (10, 50, 100, 200):
    f10.append(dict(copy.deepcopy(BASE), age_tau=t, label=f"f10_tau{t}"))
for c in (0.5, 2.0):
    b = copy.deepcopy(BASE)
    b["borrow"]["cap_rel"] = c
    f10.append(dict(b, label=f"f10_cap{c}"))
for w in (100, 500):
    f10.append(dict(copy.deepcopy(BASE), window=w, label=f"f10_window{w}"))
for k in ("a01_local_geometric", "a03_smooth_alternating"):
    syn(f"f10_{k}", *D[k], methods=f10, seeds=50)
# Region count
pk = [m for m in SYN if m["label"] in ("regional_aci_g0.05_p", "olcp_g0.02", "dalo_agei25_e0.05_b")]
for K, n in ((2, 6000), (3, 8000), (6, 12000), (10, 20000)):
    delays = [1 if r % 2 == 0 else 50 * K for r in range(K)]
    syn(f"f10_regions{K}", dict(TWO, n_regions=K, n_rounds=n, region_weights=None), {"type": "geometric", "per_region": delays, "d_max": 250 * K},
        [{"kind": "mean", "size_per_region": [0.6] * K, "start": n // 2, "profile": "abrupt"}], methods=pk, seeds=50)
print(len(glob.glob(str(OUT / "m5_*.yaml"))), "configs")
