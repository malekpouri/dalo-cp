"""Writes configs/experiments/m5_trace_{p,d}.yaml. Protocol: reports/decisions.md (TRACE protocol). Nothing is tuned on TRACE."""
import copy
from pathlib import Path

import yaml

OUT = Path("configs/experiments")
METHODS = yaml.safe_load(open(OUT / "m5_elec2.yaml"))["methods"]
REF = {"use": "regional_aci", "gamma": 0.005, "project": True, "oracle_no_delay": True, "label": "regional_aci_oracle"}
for part in ("P", "D"):
    exp = {"name": f"m5_trace_{part.lower()}", "alpha": 0.1, "dataset": {"use": "trace", "partition": part}, "delay": {"type": "real"}, "shifts": [],
           "eval": {"window": 100, "burn_in": 500}, "runtime": {"log_every": 2000}, "methods": copy.deepcopy(METHODS) + [REF],
           "seeds": {"start": 3000, "count": 10}}
    (OUT / f"m5_trace_{part.lower()}.yaml").write_text("# Generated by scripts/make_m5_trace_configs.py.\n" + yaml.safe_dump(exp, sort_keys=False))
