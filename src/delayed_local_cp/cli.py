"""Command-line entry point: ``python -m delayed_local_cp.cli <command>``."""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
from datetime import datetime
from pathlib import Path

from .experiments import sweep
from .experiments.runner import run_dir_for, run_single
from .tracking.registry import Registry
from .utils.gitinfo import git_commit, recent_commits
from .utils.paths import CONFIGS_DIR, REPORTS_DIR

REQUIRED_RUN_FILES = ("config.yaml", "metrics.jsonl", "summary.json", "run.log", "rounds.npz")


def _fmt(v, nd=3):
    if v is None:
        return "-"
    if isinstance(v, str):
        return v
    if isinstance(v, float) and not math.isfinite(v):
        return str(v)
    return f"{v:.{nd}f}"


def cmd_run(args) -> int:
    import yaml

    with open(args.config, encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh)
    print(run_single(cfg))
    return 0


def cmd_sweep(args) -> int:
    exp = sweep.load_experiment(args.config)
    cfgs = sweep.expand(exp)
    print(f"experiment {exp['name']}: {len(cfgs)} runs, jobs={args.jobs}")
    res = sweep.execute(cfgs, jobs=args.jobs)
    bad = {k: v for k, v in res.items() if v != "completed"}
    print(f"completed {len(res) - len(bad)}/{len(cfgs)}")
    for k, v in bad.items():
        print(f"  {v}: {k}")
    return 0 if not bad else 1


def cmd_resume(args) -> int:
    reg = Registry()
    stale = reg.mark_stale()
    if stale:
        print(f"marked {len(stale)} stale runs as interrupted")
    state = REPORTS_DIR / "STATE.md"
    if state.exists():
        print("---- reports/STATE.md ----")
        print(state.read_text(encoding="utf-8").strip())
        print("--------------------------")
    cfgs = sweep.pending_from_registry(reg)
    print(f"registry: {reg.counts()}; {len(cfgs)} queued/interrupted runs to (re)start")
    if not cfgs:
        return 0
    res = sweep.execute(cfgs, jobs=args.jobs, registry=reg)
    bad = {k: v for k, v in res.items() if v != "completed"}
    print(f"completed {len(res) - len(bad)}/{len(cfgs)}")
    return 0 if not bad else 1


def cmd_smoke(args) -> int:
    exp = sweep.load_experiment(CONFIGS_DIR / "experiments" / "smoke.yaml")
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    cfgs = sweep.expand(exp, name_suffix=f"-{stamp}")
    t0 = time.time()
    res = sweep.execute(cfgs, jobs=args.jobs)
    problems = []
    rows = []
    for cfg in cfgs:
        rd = run_dir_for(cfg)
        missing = [f for f in REQUIRED_RUN_FILES if not (rd / f).exists()]
        if res.get(cfg["run_id"]) != "completed" or missing:
            problems.append(f"{cfg['run_id']}: status={res.get(cfg['run_id'])} missing={missing}")
            continue
        s = json.loads((rd / "summary.json").read_text())
        rows.append((s["method"], s["seed"], s["marginal_coverage"], s["worst_region_window_coverage"],
                     s["mean_width"], s["regional_coverage"]))
    print(f"\nsmoke experiment {cfgs[0]['experiment']} ({len(cfgs)} runs, {time.time() - t0:.1f}s)")
    print(f"{'method':24s} {'seed':>4s} {'marginal':>9s} {'worst-rw':>9s} {'width':>7s}  regional")
    for m, sd, mc, wr, wd, rc in rows:
        print(f"{m:24s} {sd:4d} {_fmt(mc):>9s} {_fmt(wr):>9s} {_fmt(wd):>7s}  {[round(c, 3) for c in rc]}")
    if problems:
        print("SMOKE FAILED:")
        for p in problems:
            print("  " + p)
        return 1
    print("SMOKE OK (end-to-end pipeline; these numbers are not results)")
    return 0


def cmd_status(args) -> int:
    reg = Registry()
    reg.mark_stale()
    print(f"registry counts: {reg.counts()}")
    for row in reg.list()[-args.n:]:
        print(f"{row['status']:12s} {_fmt(row['progress'], 2):>5s} {row['run_id']}")
    return 0


def cmd_report(args) -> int:
    import yaml

    reg = Registry()
    reg.mark_stale()
    ms_path = REPORTS_DIR / "milestones.yaml"
    ms = yaml.safe_load(ms_path.read_text()) if ms_path.exists() else {}
    now = datetime.now()
    lines = [f"# Status snapshot {now:%Y-%m-%d %H:%M}", "",
             "Automatic snapshot generated by `make report`. Narrative milestone reports are written separately.", "",
             f"- Current milestone: {ms.get('current', 'unknown')}",
             f"- Git commit: `{git_commit()}`",
             f"- Run registry: {reg.counts()}", "", "## Recent commits", ""]
    lines += [f"- `{c['commit']}` {c['date']} {c['message']}" for c in recent_commits(10)]
    lines += ["", "## Recent runs", ""]
    for row in reg.list()[-15:]:
        lines.append(f"- {row['status']}: `{row['run_id']}`")
    text = "\n".join(lines) + "\n"
    out = REPORTS_DIR / "progress" / f"{now:%Y-%m-%d_%H%M}_status-snapshot.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"written to {out.relative_to(REPORTS_DIR.parent)}")
    return 0


def cmd_figures(args) -> int:
    from .figures.paper import main

    return main()


def cmd_analyze(args) -> int:
    if args.name == "m2":
        from .evaluation.feasibility import main as m2

        res = m2()
        return 0 if res["gate"]["pass"] else 3
    if args.name == "m2b":
        from .evaluation.feasibility import main as m2

        res = m2("m2b_confirm", metric="worst")
        return 0 if res["gate"]["pass"] else 3
    if args.name.startswith("m3"):
        from .evaluation.m3 import main as m3

        return m3(args.name)
    if args.name == "trace":
        from .data.trace import diagnostics

        res = diagnostics()
        print(json.dumps({k: res[k] for k in ("C1", "C2", "delay_overall", "partitions", "outcome", "primary_partitions")}, indent=2))
        return 0
    print(f"unknown analysis {args.name!r}")
    return 2


def cmd_prepare(args) -> int:
    if args.name == "elec2":
        from .data.elec2 import prepare

        print(json.dumps(prepare(), indent=2))
        return 0
    if args.name == "trace":
        from .data.trace import prepare

        print(json.dumps(prepare(), indent=2))
        return 0
    if args.name == "trace_models":
        from .data.trace import build_models

        print(json.dumps(build_models(), indent=2))
        return 0
    print(f"unknown dataset {args.name!r}")
    return 2


def cmd_release(args) -> int:
    from .release import main as release

    return release()


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="delayed_local_cp")
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("run", help="run one resolved config.yaml")
    s.add_argument("--config", required=True)
    s.set_defaults(fn=cmd_run)
    s = sub.add_parser("sweep", help="expand and run an experiment config")
    s.add_argument("--config", required=True)
    s.add_argument("--jobs", type=int, default=4)
    s.set_defaults(fn=cmd_sweep)
    s = sub.add_parser("resume", help="restart queued and interrupted runs")
    s.add_argument("--jobs", type=int, default=4)
    s.set_defaults(fn=cmd_resume)
    s = sub.add_parser("smoke", help="small end-to-end synthetic run")
    s.add_argument("--jobs", type=int, default=2)
    s.set_defaults(fn=cmd_smoke)
    s = sub.add_parser("status", help="registry summary")
    s.add_argument("-n", type=int, default=20)
    s.set_defaults(fn=cmd_status)
    sub.add_parser("report", help="write a status snapshot report").set_defaults(fn=cmd_report)
    sub.add_parser("figures", help="generate figures").set_defaults(fn=cmd_figures)
    s = sub.add_parser("prepare", help="build a processed dataset (e.g. elec2)")
    s.add_argument("name")
    s.set_defaults(fn=cmd_prepare)
    s = sub.add_parser("analyze", help="milestone analyses (e.g. m2)")
    s.add_argument("name")
    s.set_defaults(fn=cmd_analyze)
    sub.add_parser("release", help="build github_repo/ (M5)").set_defaults(fn=cmd_release)
    args = p.parse_args(argv)
    return int(args.fn(args) or 0)


if __name__ == "__main__":
    sys.exit(main())
